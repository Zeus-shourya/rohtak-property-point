/* --------------------------------------------------------------------------
   Helper: build a wa.me deep link.
   -------------------------------------------------------------------------- */
window.RPP.waLink = function (text) {
  var n = (window.RPP.whatsappNumber || '').replace(/\D/g, '');
  var t = encodeURIComponent(text || window.RPP.whatsappText);
  return 'https://wa.me/' + n + '?text=' + t;
};
